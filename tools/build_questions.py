def paragraphs(path):
    xml = zipfile.ZipFile(path).read("word/document.xml").decode("utf8")
    out = []
    for p in xml.split("</w:p>"):
        t = html.unescape(re.sub(r"<[^>]+>", "", p)).strip()
        if t:
            out.append(t)
    return out

